DO $$
DECLARE
    v_admin_role_id UUID;
    v_photo_role_id UUID;
    v_perm_id UUID;
BEGIN
    SELECT id INTO v_admin_role_id FROM roles WHERE name = 'admin';
    SELECT id INTO v_photo_role_id FROM roles WHERE name = 'photographer';

    FOR v_perm_id IN SELECT id FROM permissions
    LOOP
        INSERT INTO role_permissions (role_id, permission_id)
        VALUES (v_admin_role_id, v_perm_id)
        ON CONFLICT DO NOTHING;
    END LOOP;

    INSERT INTO role_permissions (role_id, permission_id)
    SELECT v_photo_role_id, id FROM permissions WHERE name IN ('bookings.view_all', 'albums.manage')
    ON CONFLICT DO NOTHING;
END $$;

